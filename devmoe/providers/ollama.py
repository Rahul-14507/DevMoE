import time
import json
from typing import List, Dict, Any, Optional, AsyncIterator
import httpx
from .base import (
    BaseProvider,
    ProviderResponse,
    UsageStats,
    ProviderOfflineError,
    ProviderError,
)


class OllamaProvider(BaseProvider):
    """Local inference engine via Ollama (supports Gemma, Qwen Coder, DeepSeek Coder, etc.)."""

    def __init__(
        self,
        base_url: str = "http://localhost:11434",
        timeout_seconds: float = 120.0,
        enable_mock_fallback: bool = True,
    ):
        super().__init__(provider_id="ollama_local", is_local=True, is_free_tier=True)
        self.base_url = base_url.rstrip("/")
        self.timeout = timeout_seconds
        self.enable_mock_fallback = enable_mock_fallback
        self._installed_cache: List[str] = []
        self._last_probe: float = 0.0

    async def is_healthy(self) -> bool:
        """Check if local Ollama daemon is active."""
        try:
            async with httpx.AsyncClient(timeout=2.0) as client:
                res = await client.get(f"{self.base_url}/api/tags")
                return res.status_code == 200
        except Exception:
            return False

    async def list_installed_models(self) -> List[str]:
        """Query Ollama daemon for currently pulled models."""
        # Cache for 10 seconds
        if time.time() - self._last_probe < 10.0 and self._installed_cache:
            return self._installed_cache

        try:
            async with httpx.AsyncClient(timeout=3.0) as client:
                res = await client.get(f"{self.base_url}/api/tags")
                if res.status_code == 200:
                    data = res.json()
                    models = [m.get("name", "") for m in data.get("models", []) if m.get("name")]
                    self._installed_cache = models
                    self._last_probe = time.time()
                    return models
        except Exception:
            pass
        return self._installed_cache

    async def complete(
        self,
        messages: List[Dict[str, str]],
        model: Optional[str] = None,
        temperature: float = 0.7,
        max_tokens: Optional[int] = None,
        **kwargs
    ) -> ProviderResponse:
        model_name = model or "qwen2.5-coder:7b"
        start_time = time.time()

        payload = {
            "model": model_name,
            "messages": messages,
            "stream": False,
            "options": {
                "temperature": temperature,
            },
        }
        if max_tokens:
            payload["options"]["num_predict"] = max_tokens

        try:
            async with httpx.AsyncClient(timeout=self.timeout) as client:
                res = await client.post(f"{self.base_url}/api/chat", json=payload)
                if res.status_code == 200:
                    data = res.json()
                    msg = data.get("message", {}).get("content", "")
                    prompt_eval = data.get("prompt_eval_count", 0)
                    eval_count = data.get("eval_count", 0)
                    latency = round((time.time() - start_time) * 1000, 2)
                    return ProviderResponse(
                        content=msg,
                        model=model_name,
                        provider_id=self.provider_id,
                        usage=UsageStats(
                            prompt_tokens=prompt_eval,
                            completion_tokens=eval_count,
                            total_tokens=prompt_eval + eval_count,
                        ),
                        latency_ms=latency,
                    )
                else:
                    raise ProviderError(
                        f"Ollama returned HTTP {res.status_code}: {res.text}",
                        status_code=res.status_code,
                        provider_id=self.provider_id,
                    )
        except (httpx.ConnectError, httpx.TimeoutException) as e:
            if self.enable_mock_fallback:
                # Provide an informative simulated response for development / CI environments
                latency = round((time.time() - start_time) * 1000, 2)
                last_user_msg = next((m["content"] for m in reversed(messages) if m.get("role") == "user"), "")
                simulated_content = (
                    f"/* [DevMoE Simulation - Ollama Local Engine] */\n"
                    f"// Notice: Ollama daemon is not running at {self.base_url}.\n"
                    f"// In production, run `ollama serve` and `ollama run {model_name}`.\n"
                    f"// Simulated local response for task: {last_user_msg[:80]}...\n\n"
                    f"def solve_task():\n"
                    f"    # Generated by local expert: {model_name}\n"
                    f"    return 'Success from local model execution.'"
                )
                return ProviderResponse(
                    content=simulated_content,
                    model=f"{model_name}-simulated",
                    provider_id=self.provider_id,
                    usage=UsageStats(prompt_tokens=len(last_user_msg)//4, completion_tokens=50, total_tokens=len(last_user_msg)//4 + 50),
                    latency_ms=latency,
                )
            raise ProviderOfflineError(
                f"Ollama daemon at {self.base_url} is unreachable. Ensure Ollama is installed and running (`ollama serve`).",
                provider_id=self.provider_id,
            )

    async def stream_complete(
        self,
        messages: List[Dict[str, str]],
        model: Optional[str] = None,
        temperature: float = 0.7,
        max_tokens: Optional[int] = None,
        **kwargs
    ) -> AsyncIterator[str]:
        model_name = model or "qwen2.5-coder:7b"
        payload = {
            "model": model_name,
            "messages": messages,
            "stream": True,
            "options": {"temperature": temperature},
        }
        if max_tokens:
            payload["options"]["num_predict"] = max_tokens

        try:
            async with httpx.AsyncClient(timeout=self.timeout) as client:
                async with client.stream("POST", f"{self.base_url}/api/chat", json=payload) as response:
                    if response.status_code != 200:
                        raise ProviderError(f"Ollama stream HTTP {response.status_code}", status_code=response.status_code, provider_id=self.provider_id)
                    async for line in response.aiter_lines():
                        if not line:
                            continue
                        chunk = json.loads(line)
                        content = chunk.get("message", {}).get("content", "")
                        if content:
                            yield content
        except Exception:
            if self.enable_mock_fallback:
                yield f"[DevMoE Local Ollama Mock: {model_name}]\nSimulated streaming output from local model..."
            else:
                raise
